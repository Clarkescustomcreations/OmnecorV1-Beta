/**
 * Blueprint Studio — built-in materials database.
 *
 * A curated, fully-offline catalog with *real* mechanical properties so the
 * deterministic calc engine (calcEngine.ts) and the FEA bridge can consume
 * them directly — this is what keeps Sovereign mode fully functional with no
 * web access. Costs are indicative planning estimates (typical US retail,
 * 2025–2026) — live prices come from the cloud-gated web search when allowed.
 *
 * Sources for the numbers:
 *  - Softwood lumber: NDS-style *allowable* design values for No.2 grade
 *    (strengthBasis "allowable" — factors already embedded).
 *  - Metals: ASTM minimum yield/ultimate (basis "yield" — apply an explicit SF).
 *  - Plastics/filaments: manufacturer datasheet typicals (basis "ultimate",
 *    with an FDM layer-adhesion knockdown for Z-loaded prints).
 *  - Fabrics/foams: supplier-typical weights/rolls (no structural strengths —
 *    used for yardage, mass, and cost planning).
 */
import type { MaterialCategory, MaterialEntry } from "@shared/blueprint";

const IN = 25.4; // mm per inch
const FT = 304.8; // mm per foot

/** Standard dimensional-lumber lengths sold at US yards. */
const LUMBER_LENGTHS = [8, 10, 12, 16].map((ft) => ft * FT);

function lumberSizes(
  sectionWmm: number,
  sectionHmm: number,
  nominal: string,
  costPerLength: Record<number, number>,
): MaterialEntry["stockSizes"] {
  return LUMBER_LENGTHS.map((len, i) => ({
    label: `${nominal} × ${[8, 10, 12, 16][i]} ft`,
    lengthMm: len,
    sectionWidthMm: sectionWmm,
    sectionHeightMm: sectionHmm,
    typicalCostUsd: costPerLength[[8, 10, 12, 16][i]],
  }));
}

