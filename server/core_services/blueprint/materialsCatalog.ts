const byKey = new Map(MATERIALS_CATALOG.map((m) => [m.key, m]));

export function getMaterial(key: string): MaterialEntry | undefined {
  return byKey.get(key);
}

export function listCategories(): MaterialCategory[] {
  return [...new Set(MATERIALS_CATALOG.map((m) => m.category))];
}

/** Simple ranked text search over name/description/tags/key. */
export function searchMaterials(query: string, category?: MaterialCategory, limit = 20): MaterialEntry[] {
  const q = query.trim().toLowerCase();
  const pool = category ? MATERIALS_CATALOG.filter((m) => m.category === category) : MATERIALS_CATALOG;
  if (!q) return pool.slice(0, limit);
  const terms = q.split(/\s+/).filter(Boolean);
  const scored = pool
    .map((m) => {
      const hay = `${m.key} ${m.name} ${m.description} ${m.tags.join(" ")}`.toLowerCase();
      let score = 0;
      for (const t of terms) {
        if (m.name.toLowerCase().includes(t)) score += 3;
        else if (m.tags.some((tag) => tag.includes(t))) score += 2;
        else if (hay.includes(t)) score += 1;
      }
      return { m, score };
    })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.m);
}
